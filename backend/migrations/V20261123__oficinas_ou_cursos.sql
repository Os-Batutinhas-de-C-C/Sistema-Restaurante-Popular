BEGIN;

CREATE TABLE IF NOT EXISTS oficinas_ou_cursos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    versao BIGINT NOT NULL DEFAULT 0,
    title VARCHAR(60) NOT NULL,
    tipo VARCHAR(10) NOT NULL CHECK (tipo IN ('OFICINA', 'CURSO')),
    vagas NUMERIC NOT NULL CHECK (vagas > 0 AND vagas = trunc(vagas)),
    descricao TEXT NOT NULL,
    data DATE NOT NULL,
    hora_inicio TIME NOT NULL,
    hora_fim TIME NOT NULL CHECK (hora_fim > hora_inicio),
    local VARCHAR(150) NOT NULL,
    instrutor VARCHAR(150) NOT NULL,
    custo VARCHAR(10) NOT NULL CHECK (custo IN ('PAGO', 'GRATUITO'))
);

CREATE TABLE IF NOT EXISTS inscricoes_oficinas_ou_cursos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id BIGINT NOT NULL REFERENCES oficinas_ou_cursos(id) ON DELETE CASCADE,
    cpf VARCHAR(11) NOT NULL,
    data_nascimento DATE NOT NULL,
    email TEXT NOT NULL,
    CONSTRAINT uk_oficina_inscricao_cpf UNIQUE (evento_id, cpf)
);

CREATE INDEX IF NOT EXISTS idx_oficinas_programacao ON oficinas_ou_cursos (data, hora_inicio, id);
CREATE INDEX IF NOT EXISTS idx_oficinas_inscricoes_cpf ON inscricoes_oficinas_ou_cursos (cpf, data_nascimento);

COMMIT;
